import { AsyncLocalStorage } from "node:async_hooks";
import { mkdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import pg from "pg";

// Postgres in production (Supabase, DATABASE_URL). Without a URL the same schema runs on PGlite, Postgres inside this
// process: in memory for tests, or in a folder for local work, so nobody writes to the live database by accident.
const SCHEMA = `
  CREATE TABLE IF NOT EXISTS users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE,
    full_name text NOT NULL,
    role text NOT NULL CHECK (role IN ('student', 'faculty', 'admin')),
    password_hash text NOT NULL,
    created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
  );
  CREATE TABLE IF NOT EXISTS sessions (
    token_hash text PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at bigint NOT NULL
  );
  CREATE TABLE IF NOT EXISTS equipment (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    category text NOT NULL,
    quantity integer NOT NULL CHECK (quantity >= 0),
    available integer CHECK (available >= 0 AND available <= quantity),
    asset_id text NOT NULL DEFAULT '',
    location text NOT NULL DEFAULT 'Main store',
    created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    updated_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
  );
  CREATE TABLE IF NOT EXISTS borrow_requests (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id integer NOT NULL REFERENCES equipment(id) ON DELETE RESTRICT,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    borrow_date text NOT NULL,
    return_date text NOT NULL,
    purpose text,
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'returned', 'cancelled')),
    returned_at text,
    created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
    decided_by integer,
    decided_at text,
    decision_reason text
  );
  CREATE INDEX IF NOT EXISTS borrow_requests_user_id ON borrow_requests (user_id, id);
  -- One pending request per user and item (SCRUM-46). Requests run in parallel on Postgres, so the database keeps the rule.
  CREATE UNIQUE INDEX IF NOT EXISTS borrow_requests_one_pending ON borrow_requests (user_id, equipment_id) WHERE status = 'pending';
  CREATE TABLE IF NOT EXISTS notifications (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    type text NOT NULL,
    title text NOT NULL DEFAULT '',
    message text NOT NULL,
    reason text,
    request_id integer,
    read_at text,
    created_at text NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
  );
  CREATE INDEX IF NOT EXISTS notifications_user_id ON notifications (user_id, id);
  -- Reminders and submission notices are sent once per user and request, even when two polls or two requests race.
  CREATE UNIQUE INDEX IF NOT EXISTS notifications_once ON notifications (user_id, request_id, type) WHERE request_id IS NOT NULL AND type IN ('due_soon', 'request_submitted');
  -- A new item has nothing on loan, so everything it owns is available; it also gets an asset ID from its id.
  CREATE OR REPLACE FUNCTION equipment_defaults() RETURNS trigger AS $$
  BEGIN
    NEW.available := COALESCE(NEW.available, NEW.quantity);
    IF NEW.asset_id = '' THEN
      NEW.asset_id := 'CG-' || CASE WHEN NEW.id < 10000 THEN lpad(NEW.id::text, 4, '0') ELSE NEW.id::text END;
    END IF;
    RETURN NEW;
  END $$ LANGUAGE plpgsql;
  CREATE OR REPLACE TRIGGER equipment_defaults BEFORE INSERT ON equipment FOR EACH ROW EXECUTE FUNCTION equipment_defaults();
  -- Supabase serves every table in public over its REST API. With RLS on and no policy, the anon key reads nothing;
  -- the owner role this app connects as bypasses RLS, so the app is not affected.
  ALTER TABLE users ENABLE ROW LEVEL SECURITY;
  ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
  ALTER TABLE equipment ENABLE ROW LEVEL SECURITY;
  ALTER TABLE borrow_requests ENABLE ROW LEVEL SECURITY;
  ALTER TABLE notifications ENABLE ROW LEVEL SECURITY;
`;

// The code writes SQLite-style "?" placeholders; Postgres numbers them. No SQL text in this app has a literal "?".
const numbered = (sql) => {
  let n = 0;
  return sql.replace(/\?/g, () => `$${++n}`);
};

// The same small surface the code used with node:sqlite, now async: await db.prepare(sql).get / all / run, and db.exec.
// isTransaction is false on the top-level database and true on the connection a withTransaction callback receives.
function adapter(query, exec, isTransaction) {
  return {
    prepare(sql) {
      const text = numbered(sql);
      return {
        get: async (...params) => (await query(text, params)).rows[0],
        all: async (...params) => (await query(text, params)).rows,
        run: async (...params) => {
          const result = await query(text, params);
          return { changes: result.rowCount ?? result.affectedRows ?? 0, lastInsertRowid: result.rows[0]?.id };
        },
      };
    },
    exec,
    isTransaction,
  };
}

const LOCAL_HOSTS = new Set(["localhost", "127.0.0.1", "::1"]);
// pg lets sslmode and friends in the URL override the ssl option, so they are removed and TLS is decided here only.
const SSL_PARAMS = /^(ssl|sslmode|sslcert|sslkey|sslrootcert|sslnegotiation|uselibpqcompat)$/i;

// Pool settings for a Postgres URL. The URL is never logged.
export function poolConfig(url, ca = process.env.DATABASE_CA) {
  const cut = url.indexOf("?");
  const params = new URLSearchParams(cut < 0 ? "" : url.slice(cut + 1));
  for (const key of [...params.keys()]) if (SSL_PARAMS.test(key)) params.delete(key);
  const rest = params.toString();
  const connectionString = (cut < 0 ? url : url.slice(0, cut)) + (rest ? `?${rest}` : "");

  let host = "";
  try {
    // pg-connection-string lets host= parameters override the URL host, and the last one wins, so that is the host pg connects to.
    host = (params.getAll("host").at(-1) || new URL(connectionString).hostname).replace(/^\[(.+)\]$/, "$1").toLowerCase();
  } catch {} // an unreadable URL counts as remote, so it gets TLS; pg reports the real problem
  let ssl = false; // a Postgres on this machine has no certificate worth checking
  if (!LOCAL_HOSTS.has(host)) {
    // shortcut: encrypted but the server certificate is not verified; set DATABASE_CA to the Supabase CA to verify
    ssl = ca ? { ca } : { rejectUnauthorized: false };
  }
  // connectionTimeoutMillis: a paused Supabase project answers with an error instead of hanging every request.
  return { connectionString, ssl, max: 5, connectionTimeoutMillis: 10_000 };
}

// True for a postgres:// or postgresql:// URL, ignoring case and surrounding spaces.
export const isPostgresUrl = (value) => /^postgres(ql)?:\/\//i.test(String(value ?? "").trim());

let template; // the in-memory database every ":memory:" caller gets a copy of

// A PGlite folder belongs to one process: two would each keep their own copy in memory and the last to close wins.
// The lock file holds the pid of the owner. A pid that is no longer alive (crash, node --watch restart) is taken over.
const heldLocks = new Set();
let exitHook = false;
function lockFolder(folder) {
  const file = join(folder, "app.lock");
  const remove = () => {
    try {
      unlinkSync(file);
    } catch {} // already gone
  };
  for (let attempt = 0; ; attempt++) {
    try {
      writeFileSync(file, String(process.pid), { flag: "wx" });
      break;
    } catch (err) {
      if (err.code !== "EEXIST") throw err;
      let pid = NaN;
      try {
        pid = Number.parseInt(readFileSync(file, "utf8"), 10);
      } catch {} // removed by its owner in the meantime
      let alive = false;
      try {
        alive = pid > 0 && (process.kill(pid, 0), true);
      } catch (killErr) {
        alive = killErr.code === "EPERM"; // alive but owned by someone else
      }
      if (alive) {
        throw new Error(`The local database folder ${folder} is in use by process ${pid}. Stop npm run dev:server (or the other process) first, then try again. If no such process is running, delete ${file}.`);
      }
      // A stale lock is taken over once; a lock that cannot be removed (for example a folder named app.lock) must not spin forever.
      if (attempt > 0) throw new Error(`Could not take over the stale lock ${file}. Delete it, then try again.`);
      // shortcut: two processes taking over the same stale lock at the same moment can both succeed; use an OS lock if that ever matters
      remove();
    }
  }
  const release = () => {
    heldLocks.delete(release);
    remove();
  };
  heldLocks.add(release);
  if (!exitHook) {
    exitHook = true;
    process.on("exit", () => heldLocks.forEach((held) => held()));
  }
  return release;
}

export async function openDb(url) {
  if (typeof url === "string" && /^[a-z][a-z0-9+.-]*:\/\//i.test(url.trim()) && !isPostgresUrl(url)) {
    // Never used as a folder name and never printed, because it may hold a password.
    throw new Error("The database setting is a URL but not a postgres:// or postgresql:// one, so it was refused.");
  }
  if (isPostgresUrl(url)) {
    // shortcut: no statement_timeout, a stuck lock wait holds a pool slot; add one once the Supabase pooler is confirmed to accept it
    const pool = new pg.Pool(poolConfig(url.trim()));
    // An idle connection dropped by the server emits "error" on the pool; unhandled, it would crash the process.
    pool.on("error", (err) => console.error("Postgres connection error:", err.message));
    await pool.query(SCHEMA);
    const db = adapter((text, params) => pool.query(text, params), (sql) => pool.query(sql), false);
    db.transaction = async (fn) => {
      const client = await pool.connect();
      let broken; // a client that lost its connection or could not roll back is in an unknown state, so the pool must drop it
      // pool.query listens for errors on its own clients; a checked-out client needs a listener here or a dropped
      // connection would crash the process instead of failing this request.
      const onLost = (err) => (broken ??= err);
      client.on?.("error", onLost);
      try {
        await client.query("BEGIN");
        const result = await fn(adapter((text, params) => client.query(text, params), (sql) => client.query(sql), true));
        await client.query("COMMIT");
        return result;
      } catch (err) {
        await client.query("ROLLBACK").catch((rollbackErr) => (broken = rollbackErr));
        throw err;
      } finally {
        client.off?.("error", onLost);
        client.release(broken);
      }
    };
    db.close = () => pool.end();
    return db;
  }
  // ":memory:" or no path: a fresh database for one test file. Any other value is a folder for local work.
  let lite;
  let release = () => {};
  // Loaded here, not at the top, so a production install without dev dependencies starts with DATABASE_URL.
  const { PGlite } = await import("@electric-sql/pglite");
  if (url && url !== ":memory:") {
    mkdirSync(url, { recursive: true }); // PGlite does not create a missing data/ parent on a fresh checkout
    release = lockFolder(url);
    try {
      lite = await PGlite.create(url);
      await lite.exec(SCHEMA);
    } catch (err) {
      release();
      throw err;
    }
  } else {
    // A fresh PGlite takes 2 to 3 s to start; a clone of one built per process takes well under 1 s.
    template ??= PGlite.create().then(async (base) => (await base.exec(SCHEMA), base));
    lite = await (await template).clone();
  }
  const db = adapter((text, params) => lite.query(text, params), (sql) => lite.exec(sql), false);
  // PGlite runs one transaction at a time, which keeps parallel test requests in order like the real database's locks.
  db.transaction = (fn) => lite.transaction((tx) => fn(adapter((text, params) => tx.query(text, params), (sql) => tx.exec(sql), true)));
  db.close = async () => {
    await lite.close();
    release();
  };
  return db;
}

// Runs fn as one transaction: all of its writes land, or none do. fn receives the database to use inside it.
// A nested call would deadlock on PGlite and commit on its own pool connection on pg, so it is refused.
const activeTransaction = new AsyncLocalStorage();
export async function withTransaction(db, fn) {
  const outer = activeTransaction.getStore();
  if (db.isTransaction || (outer?.db === db && outer.open)) {
    throw new Error("withTransaction cannot run inside another transaction; use the connection it gave you.");
  }
  // open ends with the transaction, so a timer or listener created inside it may start its own transaction later.
  const store = { db, open: true };
  try {
    return await activeTransaction.run(store, () => db.transaction(fn));
  } finally {
    store.open = false;
  }
}

// Postgres integer ids stop at 2147483647; a bigger number in a URL or body is a row that cannot exist, not a crash.
export const isId = (value) => Number.isInteger(value) && value >= 1 && value <= 2147483647;
